"""
Builds books.html and every page in books/ from the list below.

To re-rank: move a book's block up or down. Its position = its rank.
To add your opinion: fill in "take".
To add a book: copy a block, put its cover in images/books/<slug>.jpg.
Then run:   python3 _build_books.py
(GitHub Pages skips files starting with "_", so this script is never published.)
"""
import html, os

BOOKS = [
    dict(slug="the-brothers-karamazov", title="The Brothers Karamazov", by="Fyodor Dostoevsky", year="1880",
         about="Three brothers and their dissolute father are pulled toward a murder, and into Dostoevsky's deepest arguments about faith, doubt and freedom.",
         take=""),
    dict(slug="crime-and-punishment", title="Crime and Punishment", by="Fyodor Dostoevsky", year="1866",
         about="A poor former student in St Petersburg kills a pawnbroker to test a theory about extraordinary men, then has to live with what he has done.",
         take=""),
    dict(slug="demons", title="Demons", by="Fyodor Dostoevsky", year="1872",
         about="A circle of young radicals in a provincial Russian town plots revolution, and their nihilism ends in murder. Also published as The Possessed and Devils.",
         take=""),
    dict(slug="white-nights", title="White Nights", by="Fyodor Dostoevsky", year="1848",
         about="A lonely dreamer meets a young woman on the streets of St Petersburg, and over four summer nights he falls in love.",
         take=""),
    dict(slug="sapiens", title="Sapiens", by="Yuval Noah Harari", year="2011",
         about="A history of humankind, from foraging bands to empires and capitalism, built around the shared stories that let strangers cooperate.",
         take=""),
]

ROOT = os.path.dirname(os.path.abspath(__file__))
e = html.escape


def head(title, up):
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)} · Shreshta Sinha</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="{up}style.css">
</head>
<body>
<div class="wrap">
  <aside class="side"><nav>
    <a href="{up}index.html">About</a>
    <a href="{up}work.html">Work</a>
    <a href="{up}books.html" class="on">Books</a>
    <a href="{up}films.html">Films</a>
    <a href="{up}blog.html">Blog</a>
  </nav></aside>
"""


TAIL = "</div>\n</body>\n</html>\n"


def build():
    items = "\n".join(f"""    <a class="item ranked" href="books/{b['slug']}.html">
      <i class="rank">{i:02d}</i>
      <img class="thumb" src="images/books/{b['slug']}.jpg" alt="{e(b['title'])} cover">
      <div><b>{e(b['title'])}</b><span>{e(b['by'])} · {b['year']}</span></div>
    </a>""" for i, b in enumerate(BOOKS, 1))
    with open(os.path.join(ROOT, "books.html"), "w") as out:
        out.write(head("Books", "") + """
  <!-- This page is generated by _build_books.py. Edit the list there, then run it. -->
  <main class="list">
""" + items + "\n  </main>\n" + TAIL)

    os.makedirs(os.path.join(ROOT, "books"), exist_ok=True)
    n = len(BOOKS)
    for i, b in enumerate(BOOKS):
        prev_, next_ = BOOKS[i - 1], BOOKS[(i + 1) % n]
        take = e(b["take"]) if b["take"] else '<span class="quiet">Coming soon.</span>'
        with open(os.path.join(ROOT, "books", b["slug"] + ".html"), "w") as out:
            out.write(head(b["title"], "../") + f"""
  <main class="film">
    <a class="back" href="../books.html">← Books</a>
    <div class="film-top">
      <img class="big" src="../images/books/{b['slug']}.jpg" alt="{e(b['title'])} cover">
      <div>
        <p class="rank-big">#{i + 1} of {n}</p>
        <h1>{e(b['title'])}</h1>
        <p class="quiet">{e(b['by'])} · {b['year']}</p>
      </div>
    </div>

    <p>{e(b['about'])}</p>

    <h2>My take</h2>
    <p>{take}</p>

    <nav class="pager">
      <a class="u" href="{prev_['slug']}.html">← {e(prev_['title'])}</a>
      <a class="u" href="{next_['slug']}.html">{e(next_['title'])} →</a>
    </nav>
  </main>
""" + TAIL)
    print(f"built books.html and {n} book pages")


if __name__ == "__main__":
    build()
